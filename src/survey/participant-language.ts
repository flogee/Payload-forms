// Translate built-in interface copy only. Authored survey text keeps its original value.
export function participantText(language: ParticipantLanguage) {
  return (german: string, ...values: (string | number | undefined)[]) => {
    const copy = language === 'en' && Object.hasOwn(english, german) ? english[german] : german
    return values.length ? copy.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? '')) : copy
  }
}

export function participantError(language: ParticipantLanguage, message: string | undefined, fallback: string) {
  return participantText(language)(message && (language === 'de' || Object.hasOwn(english, message)) ? message : fallback)
}
